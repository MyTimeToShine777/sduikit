// Writes docs/widgets.md: one entry per widget, built from the schema files so it cannot be out of date.
// Run `npm run docs` after changing a widget schema or schemas/catalogue.json.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const readJson = (relative) => JSON.parse(readFileSync(join(repoRoot, relative), "utf8"));

// A short plain description of what one field of a widget holds.
function describe(schema) {
  if (schema.$ref) {
    const token = /tokens\.json#\/\$defs\/(\w+)$/.exec(schema.$ref);
    if (token) return `${token[1]} name`;
    if (schema.$ref.endsWith("widget.json")) return "a widget";
    if (schema.$ref.endsWith("action.json")) return "an action";
    return "see schema";
  }
  if (schema.enum) return schema.enum.map((value) => `\`${value}\``).join(" or ");
  switch (schema.type) {
    case "string":
      if (schema.format === "uri") return "web address";
      if (schema.format === "date-time") return "date and time (UTC)";
      return "text";
    case "integer":
    case "number": {
      const kind = schema.type === "integer" ? "whole number" : "number";
      const low = schema.minimum ?? schema.exclusiveMinimum;
      const range = low !== undefined || schema.maximum !== undefined ? ` (${low ?? "…"} to ${schema.maximum ?? "…"})` : "";
      return kind + range;
    }
    case "boolean":
      return "true or false";
    case "array": {
      const inner = describe(schema.items ?? {});
      const size = schema.minItems ? `, at least ${schema.minItems}` : "";
      return `list of ${inner}${schema.maxItems ? `, at most ${schema.maxItems}` : ""}${size}`;
    }
    case "object": {
      const inner = Object.entries(schema.properties ?? {});
      return inner.length ? `object with ${inner.map(([key]) => `\`${key}\``).join(", ")}` : "object";
    }
    default:
      return "any";
  }
}

export function buildWidgetDocs() {
  const catalogue = readJson("schemas/catalogue.json");
  const groupOrder = ["Basics", "Layout", "Media", "Content", "Interactive", "Live data"];
  const lines = [
    "# Widget reference",
    "",
    "<!-- Generated by scripts/generate-widget-docs.mjs from the files in /schemas. Do not edit by hand; run `npm run docs`. -->",
    "",
    `The built-in widgets (${Object.keys(catalogue.types).length}), grouped by what they are for. Every widget has the same outer shape`,
    "(`id`, `type`, `v`, `data`, and the optional `style`, `action`, `analytics`, `rules`, `fallback`; see the README). The tables below describe",
    "the `data` of each widget. A field marked **required** must be there; the others may be left out.",
    "",
  ];
  for (const group of groupOrder) {
    const inGroup = Object.entries(catalogue.types).filter(([, entry]) => entry.group === group);
    if (!inGroup.length) continue;
    lines.push(`## ${group}`, "");
    for (const [type, entry] of inGroup) {
      const versions = Object.keys(entry.versions).join(", ");
      const file = Object.values(entry.versions).at(-1).schema;
      const schema = readJson(`schemas/${file}`);
      const required = new Set(schema.required ?? []);
      lines.push(`### \`${type}\``, "", `${entry.description} (version ${versions})`, "");
      if (schema.description) lines.push(schema.description, "");
      const properties = Object.entries(schema.properties ?? {});
      if (properties.length) {
        lines.push("| Field | Holds | |", "|---|---|---|");
        for (const [key, property] of properties) {
          lines.push(`| \`${key}\` | ${describe(property)} | ${required.has(key) ? "**required**" : ""} |`);
        }
      } else {
        lines.push("No fields.");
      }
      lines.push("");
    }
  }
  return lines.join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(join(repoRoot, "docs", "widgets.md"), buildWidgetDocs());
  console.log("Wrote docs/widgets.md");
}
